import { test, expect } from "@playwright/test";
import { sansSyntheseAlertes } from "./aides";

test.use({ storageState: "e2e/.auth/superadmin.json" });
test("le dirigeant modifie une durée, retrouve sa trace et la rétablit", async ({ page, baseURL }) => {
  if (!baseURL || !["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("Recette de modification réservée au banc local");
  await sansSyntheseAlertes(page);
  await page.goto("/admin/conservation");
  await expect(page.getByRole("heading", { name: "Durées de conservation", exact: true })).toBeVisible();
  const categories = page.getByRole("list", { name: "Catégories de conservation" });
  await expect(categories.locator("li")).toHaveCount(6);
  const premiere = await categories.locator("li").first().innerText();
  await page.getByRole("button", { name: "Suivante", exact: true }).click();
  await expect(page.getByText("Page 2 sur", { exact: false })).toBeVisible();
  await expect(categories.locator("li").first()).not.toHaveText(premiere);
  await page.getByRole("searchbox").fill("technique");
  await expect(categories.locator("li")).toHaveCount(1);
  const ligne = page.locator("li").filter({ has: page.getByRole("button", { name: /^Modifier/ }) }).first();
  await ligne.getByRole("button").click();
  const formulaire = page.getByRole("form", { name: /^Modifier/ });
  const champ = formulaire.getByLabel("Nouvelle durée en mois");
  const ancienne = Number(await champ.inputValue());
  const nouvelle = ancienne === 9 ? 8 : 9;
  await champ.fill(String(nouvelle));
  await formulaire.getByLabel("Raison du changement").fill("Recette navigateur locale de la durée technique");
  await expect(formulaire.getByRole("button", { name: "Enregistrer la durée" })).toBeDisabled();
  await formulaire.getByRole("checkbox").check();
  await formulaire.getByRole("button", { name: "Enregistrer la durée" }).click();
  await expect(formulaire.getByRole("status")).toContainText("Durée enregistrée");
  const historique = page.locator("details").filter({ has: page.getByRole("heading", { name: "Historique des durées", exact: true }) });
  await historique.locator("summary").click();
  await expect(historique.getByText("Recette navigateur locale de la durée technique", { exact: true }).first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "e2e/.results/durees-enregistrees-mobile.png", fullPage: false });
  await formulaire.getByRole("button", { name: "Fermer" }).click();
  await page.goto("/confidentialite#durees-actuelles");
  await expect(page.getByRole("region", { name: "Durées modifiées depuis la V1" })).toContainText(`${nouvelle} mois`);
  await page.goto("/admin/conservation");
  await page.getByRole("searchbox").fill("technique");
  await page.locator("li").filter({ has: page.getByRole("button", { name: /^Modifier/ }) }).first().getByRole("button").click();
  await champ.fill(String(ancienne));
  await formulaire.getByLabel("Raison du changement").fill("Fin de recette : retour à la durée initiale");
  await formulaire.getByRole("checkbox").check();
  await formulaire.getByRole("button", { name: "Enregistrer la durée" }).click();
  await expect(formulaire.getByRole("status")).toContainText("Durée enregistrée");
  await formulaire.getByRole("button", { name: "Fermer" }).click();
  await page.reload();
  await historique.locator("summary").click();
  await expect(historique.getByText("Fin de recette : retour à la durée initiale", { exact: true }).first()).toBeVisible();
});
