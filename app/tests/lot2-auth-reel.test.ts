import {Client} from 'pg';
import {createClient} from '@supabase/supabase-js';
import {randomUUID,createHash} from 'node:crypto';
import {beforeAll,afterAll,it,expect} from 'vitest';
const endpoint=process.env.GERIMMO_AUTH_REEL_URL, url=process.env.GERIMMO_AUTH_REEL_DB;
if(endpoint!=='http://127.0.0.1:55519'||!url?.endsWith('@127.0.0.1:55449/gerimmo_ci_auth_reprise'))throw Error('Service fictif local exigé');
const db=new Client({connectionString:url});
const client=()=>createClient(endpoint,process.env.GERIMMO_AUTH_REEL_SERVICE!,{global:{fetch:(input,init)=>fetch(String(input).replace('/auth/v1/','/'),init)},auth:{persistSession:false,autoRefreshToken:false}});
const admin=client(),ids:string[]=[];const hash=(v:string)=>createHash('sha256').update(v).digest('hex');
beforeAll(async()=>{await db.connect();});
afterAll(async()=>{for(const id of ids)await admin.auth.admin.deleteUser(id);await db.end();});
it('inscription, lien unique, mot de passe, récupération et ancien lien invalide avec GoTrue local',async()=>{
 const email=randomUUID()+'@example.invalid',password='Fictif-securise-'+randomUUID();
 const lien=await admin.auth.admin.generateLink({type:'signup',email,password});expect(lien.error).toBeNull();ids.push(lien.data.user!.id);
 const token=lien.data.properties!.hashed_token;
 const row=(await db.query('select confirmation_token,confirmation_sent_at from auth.users where id=$1',[lien.data.user!.id])).rows[0];
 expect(hash(row.confirmation_token)).toBe(hash(token));expect(row.confirmation_sent_at).toBeInstanceOf(Date);
 const session=client();expect((await session.auth.signInWithPassword({email,password})).error).not.toBeNull();
 expect((await session.auth.verifyOtp({type:'signup',token_hash:token})).error).toBeNull();
 expect((await client().auth.verifyOtp({type:'signup',token_hash:token})).error).not.toBeNull();
 expect((await session.auth.signInWithPassword({email,password})).error).toBeNull();
 const recovery=await admin.auth.admin.generateLink({type:'recovery',email});expect(recovery.error).toBeNull();
 const recoveryToken=recovery.data.properties!.hashed_token;
 const r=(await db.query('select recovery_token,recovery_sent_at from auth.users where id=$1',[lien.data.user!.id])).rows[0];expect(hash(r.recovery_token)).toBe(hash(recoveryToken));
 expect((await session.auth.verifyOtp({type:'recovery',token_hash:recoveryToken})).error).toBeNull();
 expect((await session.auth.updateUser({password:password+'-nouveau'})).error).toBeNull();
 expect((await client().auth.signInWithPassword({email,password})).error).not.toBeNull();
 expect((await client().auth.signInWithPassword({email,password:password+'-nouveau'})).error).toBeNull();
 expect((await client().auth.verifyOtp({type:'recovery',token_hash:recoveryToken})).error).not.toBeNull();
});
it('lien expiré et compte suspendu refusés par Auth local',async()=>{
 const email=randomUUID()+'@example.invalid',password='Fictif-securise-'+randomUUID();
 const created=await admin.auth.admin.createUser({email,password,email_confirm:true});expect(created.error).toBeNull();ids.push(created.data.user!.id);
 const lien=await admin.auth.admin.generateLink({type:'recovery',email});expect(lien.error).toBeNull();
 await db.query("update auth.users set recovery_sent_at=now()-interval '25 hours' where id=$1",[created.data.user!.id]);
 await db.query("update auth.one_time_tokens set created_at=now()-interval '25 hours',updated_at=now()-interval '25 hours' where user_id=$1",[created.data.user!.id]);
 expect((await client().auth.verifyOtp({type:'recovery',token_hash:lien.data.properties!.hashed_token})).error).not.toBeNull();
 await admin.auth.admin.updateUserById(created.data.user!.id,{ban_duration:'24h'});
 expect((await client().auth.signInWithPassword({email,password})).error).not.toBeNull();
});
